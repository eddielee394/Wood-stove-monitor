// Generates the LVGL fonts and icons used by the UI into src/ui/assets/.
// The output is committed, so firmware builds never need Node. Re-run with
// `npm run gen` (in tools/) after changing a glyph set or an icon.
//
// Fonts: Plus Jakarta Sans (SIL OFL, fonts/src/OFL.txt), weights 600 and 800,
// as used by the "Wood Stove Monitor" design canvas.
// Icons: the canvas's 24x24 stroke SVGs, rendered to A8 (alpha-only) images
// so LVGL can tint them with image_recolor.

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, 'src', 'ui', 'assets');
const fontDir = join(root, 'fonts', 'src');
mkdirSync(out, { recursive: true });

// ---------------------------------------------------------------- fonts
const TEXT_SYMBOLS = '°−·–±…';
const FONTS = [
  // Big readouts: digits only keeps this one small.
  { name: 'jakarta_96_xb', file: 'ExtraBold', size: 96, symbols: '0123456789-−' },
  { name: 'jakarta_20_xb', file: 'ExtraBold', size: 20, range: '0x20-0x7E', symbols: TEXT_SYMBOLS },
  { name: 'jakarta_20_sb', file: 'SemiBold', size: 20, range: '0x20-0x7E', symbols: TEXT_SYMBOLS },
  { name: 'jakarta_14_xb', file: 'ExtraBold', size: 14, range: '0x20-0x7E', symbols: TEXT_SYMBOLS },
  { name: 'jakarta_14_sb', file: 'SemiBold', size: 14, range: '0x20-0x7E', symbols: TEXT_SYMBOLS },
];

const conv = join(here, 'node_modules', '.bin', 'lv_font_conv');
for (const f of FONTS) {
  const args = [
    '--font', join(fontDir, `PlusJakartaSans-${f.file}.ttf`),
    '--size', String(f.size), '--bpp', '4', '--format', 'lvgl', '--no-compress',
    '--lv-font-name', f.name, '-o', join(out, `${f.name}.c`),
  ];
  if (f.range) args.push('-r', f.range);
  if (f.symbols) args.push('--symbols', f.symbols);
  execFileSync(conv, args, { stdio: 'inherit' });
  console.log(`font ${f.name}`);
}

// ---------------------------------------------------------------- icons
