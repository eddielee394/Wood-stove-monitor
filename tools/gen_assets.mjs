let c = '// GENERATED by tools/gen_assets.mjs - do not edit.\n#include "icons.h"\n\n';
const CPP_OPEN = '#ifdef __cplusplus\nextern "C" {\n#endif\n\n';
const CPP_CLOSE = '\n#ifdef __cplusplus\n}\n#endif\n';
let h = '// GENERATED by tools/gen_assets.mjs - do not edit.\n#pragma once\n\n#include <lvgl.h>\n\n' + CPP_OPEN;
for (const [name, icon] of Object.entries(ICONS)) {
  for (const size of icon.sizes) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${icon.svg}</svg>`;
    const img = new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render();
    const rgba = img.pixels;
    const alpha = [];
    for (let i = 3; i < rgba.length; i += 4) alpha.push(rgba[i]);
    const id = `icon_${name}_${size}`;
    const rows = [];
    for (let y = 0; y < size; y++) {
      rows.push('  ' + alpha.slice(y * size, (y + 1) * size).map((v) => `0x${v.toString(16).padStart(2, '0')}`).join(','));
    }
    c += `static const uint8_t ${id}_map[] = {\n${rows.join(',\n')}\n};\n`;
    c += `const lv_image_dsc_t ${id} = {\n  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = ${size}, .h = ${size}, .stride = ${size}},\n  .data_size = sizeof(${id}_map),\n  .data = ${id}_map,\n};\n\n`;
    h += `extern const lv_image_dsc_t ${id};\n`;
  }
}
writeFileSync(join(out, 'icons.c'), c);
writeFileSync(join(out, 'icons.h'), h + CPP_CLOSE);

let fh = '// GENERATED by tools/gen_assets.mjs - do not edit.\n#pragma once\n\n#include <lvgl.h>\n\n' + CPP_OPEN;
for (const f of FONTS) fh += `LV_FONT_DECLARE(${f.name});\n`;
writeFileSync(join(out, 'fonts.h'), fh + CPP_CLOSE);
console.log(`icons: ${Object.values(ICONS).reduce((n, i) => n + i.sizes.length, 0)} images`);
